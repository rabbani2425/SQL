-- Get total Sales month wise
SELECT ORDER_DATE , SUM(SALES_$)
FROM SALES_DATA
GROUP BY ORDER_DATE;

-- EXTRACT MONTH NUMBER FROM DATE 

SELECT EXTRACT (MONTH FROM ORDER_DATE)
FROM SALES_DATA;

-- MONTH NAME EXTRACT 

SELECT TO_CHAR(ORDER_DATE, 'month')
FROM SALES_DATA;

-- MONTH WISE TOTAL SALES 

SELECT TO_CHAR(ORDER_DATE, 'month') , SUM(SALES_$)
FROM SALES_DATA
GROUP BY TO_CHAR(ORDER_DATE, 'month');

-- DAY WISE TOTAL SALES 

SELECT TO_CHAR(ORDER_DATE, 'DAY') , SUM(SALES_$)
FROM SALES_DATA
GROUP BY TO_CHAR(ORDER_DATE, 'DAY');

-- YEAR WISE TOTAL SALES 


SELECT TO_CHAR(ORDER_DATE, 'year') , SUM(SALES_$)
FROM SALES_DATA
GROUP BY TO_CHAR(ORDER_DATE, 'year');


-- 4. AGE FUNCTION IN SQL

