-- STRING FUNCTION

-- 1.UPPER FUNCTION

SELECT CUSTOMER_NAME ,UPPER(CUSTOMER_NAME)
FROM SALES_DATA;


-- 2.LOWER FUNCTION

SELECT CUSTOMER_NAME ,LOWER(CUSTOMER_NAME)
FROM SALES_DATA;


-- 3.LENGTH FUNCTION

SELECT CUSTOMER_NAME ,LENGTH(CUSTOMER_NAME)
FROM SALES_DATA;


-- 4. CONCAT FUNCTION

SELECT CUSTOMER_NAME, SEGMENT ,CONCAT(CUSTOMER_NAME, SEGMENT)
FROM SALES_DATA;

SELECT CUSTOMER_NAME, SEGMENT ,CONCAT(CUSTOMER_NAME,'-', SEGMENT)
FROM SALES_DATA;


-- 5. REPLACE FUNCTION

SELECT REGION, REPLACE(REGION, 'Central', 'North') AS NewZone
FROM SALES_DATA;

-- 6. SUBSTRING FUNCTION

SELECT CUSTOMER_NAME,SUBSTRING(CUSTOMER_NAME, 1,5)
FROM SALES_DATA;


-- 6. STRINGPOSTION OR STRPOS FUNCTION

SELECT CUSTOMER_NAME,STRPOS(CUSTOMER_NAME,' ')
FROM SALES_DATA;
 

-- GET SEPRATE FIRST NAME FORM CUSTOMER NAME 


SELECT CUSTOMER_NAME, SUBSTRING(CUSTOMER_NAME, 1, STRPOS(CUSTOMER_NAME,' '))
FROM SALES_DATA;


-- GET SEPRATE LAST NAME FORM CUSTOMER NAME 


SELECT CUSTOMER_NAME, SUBSTRING(CUSTOMER_NAME, STRPOS(CUSTOMER_NAME,' '), LENGTH(CUSTOMER_NAME)-STRPOS(CUSTOMER_NAME,' '))
FROM SALES_DATA;